#!/usr/bin/env python3
"""
Extract unique phonemes from deep_tongue.json and write deep_tongue_phonemes.json.

Run once to generate the phoneme inventory. After that, the output is a static
data file and should not be regenerated (glyph_seeds must remain stable).

Usage:
    python tools/extract_phonemes.py
"""
from __future__ import annotations
import json
import re
from pathlib import Path


# Recognised onset clusters (order matters — longest match first)
_ONSETS = [
    "skr", "skur",
    "vr", "sk", "gr", "kr", "zh", "dr", "mr", "qu",
]

# Recognised coda patterns
_CODAS = [
    "th", "ss", "ll", "sk", "rn", "lk", "rth",
]


def _split_word(word: str) -> list[str]:
    """
    Split a deep tongue word into phoneme tokens.
    Strategy: greedy onset match, then vowel nucleus, then greedy coda match.
    Multi-syllable words repeat the pattern.
    """
    phonemes: list[str] = []
    pos = 0
    n = len(word)

    while pos < n:
        # 1. Match onset cluster (longest first)
        onset = ""
        for cl in _ONSETS:
            if word[pos:].startswith(cl):
                onset = cl
                break
        if not onset and word[pos] not in "aeiou":
            onset = word[pos]
        pos += len(onset)

        # 2. Match vowel nucleus
        nucleus = ""
        while pos < n and word[pos] in "aeiou":
            nucleus += word[pos]
            pos += 1

        # 3. Match coda (longest first)
        coda = ""
        for cd in _CODAS:
            if word[pos:].startswith(cd):
                # Only consume coda if what follows is a consonant or end-of-word
                after = pos + len(cd)
                if after >= n or word[after] not in "aeiou":
                    coda = cd
                    break
        if not coda and pos < n and word[pos] not in "aeiou":
            # Check if next char starts a new onset cluster
            is_next_onset = False
            for cl in _ONSETS:
                if word[pos:].startswith(cl):
                    is_next_onset = True
                    break
            if not is_next_onset:
                # Single consonant coda, unless it's the start of next syllable
                if pos + 1 < n and word[pos + 1] in "aeiou":
                    pass  # leave for next syllable onset
                else:
                    coda = word[pos]
        pos += len(coda)

        syllable = onset + nucleus + coda
        if syllable:
            phonemes.append(syllable)
        elif pos < n:
            # Safety: consume one char to avoid infinite loop
            phonemes.append(word[pos])
            pos += 1

    return phonemes


def main() -> None:
    data_root = Path(__file__).resolve().parent.parent / "data"
    dt_path = data_root / "deep_tongue.json"

    with open(dt_path, encoding="utf-8") as f:
        dt = json.load(f)

    # Collect all unique phonemes across all words
    all_phonemes: dict[str, None] = {}  # ordered set
    word_decompositions: dict[str, list[str]] = {}

    for entry in dt["words"]:
        word = entry["deep"].lower()
        parts = _split_word(word)
        word_decompositions[word] = parts
        for p in parts:
            if p not in all_phonemes:
                all_phonemes[p] = None

    # Assign glyph_seeds starting at 2001
    phoneme_list = []
    for i, phoneme in enumerate(all_phonemes):
        phoneme_list.append({
            "phoneme": phoneme,
            "glyph_seed": 2001 + i,
        })

    output = {
        "note": "Phoneme inventory for deep tongue glyph rendering. Generated by tools/extract_phonemes.py. Do not regenerate — glyph_seeds are fixed.",
        "phonemes": phoneme_list,
        "word_decompositions": word_decompositions,
    }

    out_path = data_root / "deep_tongue_phonemes.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(output, f, indent=2, ensure_ascii=False)

    print(f"Extracted {len(phoneme_list)} unique phonemes from {len(dt['words'])} words.")
    print(f"Written to {out_path}")
    print()
    for word, parts in word_decompositions.items():
        print(f"  {word:12s} → {' · '.join(parts)}")


if __name__ == "__main__":
    main()
