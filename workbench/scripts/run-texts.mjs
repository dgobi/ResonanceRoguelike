import {spawnSync} from "node:child_process";
import {mkdir,writeFile} from "node:fs/promises";
import {resolve} from "node:path";
const root=resolve(".artifacts/w5b",`data-fixture-${Date.now()}`);
await mkdir(root,{recursive:true});
const fixture=spawnSync(resolve("worker/runtime/python.exe"),["-X","utf8","-B","-c","import sys;sys.path.insert(0,'worker');from test_texts import text_fixture;text_fixture(sys.argv[1])",root],{stdio:"inherit",windowsHide:true});
if(fixture.status!==0) process.exit(fixture.status || 1);
await writeFile(resolve(".artifacts/w5b/native-fixture.json"),JSON.stringify({root}));
const test=spawnSync(process.execPath,["scripts/desktop-test.mjs"],{stdio:"inherit",windowsHide:true,env:{...process.env,WORKBENCH_TEST_MODE:"texts",WORKBENCH_TEST_ROOT:root}});
process.exitCode=test.status || 0;
