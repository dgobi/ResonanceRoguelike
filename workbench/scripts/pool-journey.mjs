import assert from "node:assert/strict";
import { readFile, writeFile, stat, realpath } from "node:fs/promises";
import { resolve } from "node:path";
import { createHash } from "node:crypto";

export async function poolJourney(page, root, output, receipt) {
  assert.match(root.replaceAll("\\", "/"), /\/workbench\/\.artifacts\/w3a\/data-fixture-\d+$/);
  assert.equal(await realpath(root), resolve(root));
  const building = "roguelike/data/buildings/commercial/apothecary_a.json";
  const pool = "roguelike/data/loot_pools/alchemist_reagents.json";
  const poolId = "alchemist_reagents_w3a", buildingId = "apothecary_w3a_loot";
  const poolTarget = pool.replace("alchemist_reagents", poolId), buildingTarget = building.replace("apothecary_a", buildingId);
  const originalBuilding = await readFile(resolve(root, building)), originalPool = await readFile(resolve(root, pool));
  const originalMeta = await stat(resolve(root, pool));
  const profile = "roguelike/data/generation/settlement_profiles.json", profileBytes = await readFile(resolve(root, profile));
  const editor = () => page.locator('[data-testid="authoring"]:visible');
  const button = name => page.getByRole("button", {name, exact: true});
  const eb = name => editor().getByRole("button", {name, exact: true});
  const idle = () => page.waitForFunction(() => !document.querySelector(".status-dot.working"), null, {timeout: 30000});
  const source = async () => { await eb("Source").click(); return editor().locator("textarea.source-editor").inputValue(); };
  const shot = name => page.screenshot({path: resolve(output, name + ".png")});
  const cleanCopy = async () => {
    const text = await page.locator("body").innerText();
    for (const phrase of ["A place to understand the world", "Your world, under the lens", "Reading the living source", "Build a furnished place"]) assert(!text.includes(phrase));
  };
  const inspectPool = async () => {
    await page.getByLabel("Active layer").selectOption("specials");
    await page.getByTestId("layout-map").scrollIntoViewIfNeeded();
    const point = await page.getByTestId("layout-map").evaluate(el => {const c=JSON.parse(el.dataset.camera), r=el.getBoundingClientRect(); return {x:r.x+c.x+1.5*16*c.scale,y:r.y+c.y+1.5*16*c.scale};});
    await page.mouse.click(point.x, point.y);
    await button("Open pool alchemist_reagents").click(); await idle();
  };
  await page.getByLabel("Search ID, name or path").fill(building);
  await page.locator(`[data-asset="${building}"]`).click(); await idle();
  await eb("Begin edit").click();
  const enriched = JSON.parse(await source()); enriched.w3a_metadata = {nested: [[null, "preserved"], [true, 7]]};
  await editor().locator("textarea.source-editor").fill(JSON.stringify(enriched, null, 2));
  await eb("Save as new variant").click(); await editor().getByLabel("New variant ID").fill(buildingId);
  const parked = await source();
  await shot("structure-draft"); await cleanCopy();
  const start = performance.now(); await inspectPool(); receipt.pool_open_ms = Math.round(performance.now() - start);
  assert.equal((await source()).replace(/\r\n/g, "\n"), originalPool.toString().replace(/\r\n/g, "\n"));
  await button(/^Return to container /).click();
  assert.equal(await source(), parked);
  await inspectPool();
  assert.deepEqual(await readFile(resolve(root, pool)), originalPool);
  assert.equal((await stat(resolve(root, pool))).mtimeMs, originalMeta.mtimeMs);
  receipt.checks.push("native container link opens actual pool; open/return/reopen is byte-exact and retains the unsaved structure draft");
  await eb("Begin edit").click();
  const poolRich = JSON.parse(await source()); poolRich.w3a_metadata = {nested: [[1,null],["keep",true]]};
  const poolText = await source(), closing = poolText.lastIndexOf("}");
  await editor().locator("textarea.source-editor").fill(poolText.slice(0, closing).trimEnd() + ',\n  "w3a_metadata": ' + JSON.stringify(poolRich.w3a_metadata) + '\n' + poolText.slice(closing));
  const beforeEdit = await source(), weight = poolRich.items[0].weight + 7;
  const editStart = performance.now(); await page.getByLabel("Weight 1", {exact:true}).fill(String(weight)); receipt.table_edit_ms = performance.now() - editStart;
  const afterEdit = await source();
  assert.equal(afterEdit, beforeEdit.replace(`"weight": ${poolRich.items[0].weight}`, `"weight": ${weight}`));
  await button("Undo pool").click(); assert.equal(await source(), beforeEdit);
  await button("Redo pool").click(); assert.equal(await source(), afterEdit);
  await editor().locator("textarea.source-editor").fill('{"id":');
  await page.getByTestId("pool-disabled").filter({hasText:"Correct JSON"}).waitFor();
  assert.equal(await page.getByLabel("Minimum rolls").isDisabled(), true);
  await editor().locator("textarea.source-editor").fill(afterEdit);
  assert.equal(await button("Undo pool").isDisabled(), false);
  assert.equal(await page.getByLabel("Weight 1", {exact:true}).inputValue(), String(weight));
  await button(`Inspect ${poolRich.items[0].item_id}`).click();
  const item = await page.getByTestId("item-inspector").innerText();
  assert(item.includes("roguelike/data/items/")); assert(item.includes(poolRich.items[0].item_id));
  await shot("pool-item-trace"); await cleanCopy(); await button("Close item").click();
  await eb("Validate draft").click(); await eb("Source").click();
  await editor().locator("textarea.source-editor").fill(afterEdit + " "); await idle();
  assert.equal(await editor().getByTestId("draft-verdict").count(), 0);
  assert.equal(await eb("Review & apply").isDisabled(), true);
  await editor().locator("textarea.source-editor").fill(afterEdit);
  const broken = JSON.parse(afterEdit); broken.items[0].item_id = "w3a_missing_item";
  await editor().locator("textarea.source-editor").fill(JSON.stringify(broken, null, 2));
  await eb("Validate draft").click(); await idle();
  await editor().getByTestId("draft-verdict").filter({hasText:"Draft rejected"}).waitFor();
  await shot("pool-validation");
  await eb("Source").click(); await editor().locator("textarea.source-editor").fill(afterEdit);
  await eb("Save as new variant").click(); await editor().getByLabel("New variant ID").fill(poolId);
  await eb("Validate draft").click(); await idle();
  await editor().getByTestId("draft-verdict").filter({hasText:"Draft contract and references passed"}).waitFor();
  await eb("Review & apply").click();
  await page.getByRole("dialog", {name:"Confirm single-file apply"}).waitFor();
  await shot("pool-review"); await cleanCopy();
  await button("Confirm apply one file").click(); await idle();
  await eb("Begin edit").waitFor();
  const savedPool = await readFile(resolve(root, poolTarget));
  assert.equal(JSON.parse(savedPool).items[0].weight, weight);
  assert.deepEqual(JSON.parse(savedPool).w3a_metadata, poolRich.w3a_metadata);
  assert.deepEqual(JSON.parse(savedPool).items.slice(1), poolRich.items.slice(1));
  assert.deepEqual(await readFile(resolve(root, building)), originalBuilding);
  await button(/^Return to container /).click();
  assert.equal(await source(), parked);
  await page.getByLabel("Active layer").selectOption("specials");
  await page.getByLabel("Placed record", {exact:true}).selectOption("0");
  await page.getByLabel("Loot pool 1", {exact:true}).selectOption(poolId);
  await button("Apply container edit").click();
  assert.deepEqual(JSON.parse(await source()).special_tiles[0].loot_pools, [poolId]);
  await button("Preview draft").click(); await idle();
  await editor().getByTestId("draft-verdict").filter({hasText:"Draft contract and references passed"}).waitFor();
  const v = JSON.parse(await editor().getByTestId("draft-receipt").textContent());
  assert.equal(v.preview.passed, true);
  const [ox,oy] = v.preview.origin, container = v.preview.containers.find(c => c.x===ox+1 && c.y===oy+1);
  assert(container.items.length > 0);
  assert(container.items.every(i => poolRich.items.some(row => row.item_id === i.item_id)));
  receipt.pool_chain = {building:buildingTarget, container:{index:0,source_xy:[1,1],decor_id:container.decor_id},pool:poolTarget,
    seed:v.preview.seed,scene_seed:v.preview.scene_seed,source:v.preview.source,contents:container.items,
    scope:"Actual structure_preview → town_gen stamper → scene_generation.populate → loot_roller → ItemFactory; created items, no natural selection claim"};
  await shot("linked-production"); await cleanCopy();
  await eb("Review & apply").click(); await button("Confirm apply one file").click(); await idle();
  const savedBuilding = await readFile(resolve(root, buildingTarget));
  assert.deepEqual(JSON.parse(savedBuilding).special_tiles[0].loot_pools, [poolId]);
  assert.deepEqual(JSON.parse(savedBuilding).w3a_metadata, enriched.w3a_metadata);
  assert.deepEqual(await readFile(resolve(root, building)), originalBuilding);
  assert.deepEqual(await readFile(resolve(root, pool)), originalPool);
  assert.deepEqual(await readFile(resolve(root, profile)), profileBytes);
  receipt.checks.push("native pool span edit, undo/redo, invalid raw freeze, item source, stale verdict rejection, exact new-pool diff/apply/reopen, retained building draft, explicit new-building link and real population all passed");
  await writeFile(resolve(output,"pool-variant.json"), savedPool); await writeFile(resolve(output,"building-variant.json"), savedBuilding);
  receipt.variants = [poolTarget,buildingTarget].map((path,i)=>({path,sha256:createHash("sha256").update(i?savedBuilding:savedPool).digest("hex")}));
  const ipc = (command,args) => page.evaluate(async ({command,args}) => {try{return await window.__TAURI_INTERNALS__.invoke(command,args);}catch(error){return {error};}}, {command,args});
  for (const path of [poolTarget,buildingTarget]) {
    const opened = await ipc("open_document", {asset:path}); assert(opened.ok, JSON.stringify(opened));
    const token=opened.result.document_token, raw=opened.result.raw;
    const validated=await ipc("validate_document",{token,draft:raw+" ",variantId:null,seed:20261023}); assert(validated.result.valid);
    await writeFile(resolve(root,path),raw+"\n");
    const conflict=await ipc("apply_document",{token,reviewToken:validated.result.review_token,confirmed:true});
    assert.equal(conflict.error?.code,"EXTERNAL_MODIFICATION_CONFLICT");
    assert.equal(await readFile(resolve(root,path),"utf8"),raw+"\n"); await writeFile(resolve(root,path),raw);
  }
  for(const path of ["roguelike/data/loot_pools/../x.json","roguelike/data/loot_pools/a.json:ads","roguelike/data/loot_pools/nested/a.json","roguelike/data/loot/x.json","roguelike/saves/x.json",".git/x.json","workbench/docs/x.json"]){
    const r=await ipc("open_document",{asset:path});assert(r.error || r.ok===false,path);
  }
  receipt.checks.push("native pool and building optimistic conflicts preserve external bytes; protected and unsupported paths rejected");
  const reopened = await ipc("open_document", {asset:poolTarget}), doc = reopened.result;
  let checked = await ipc("validate_document",{token:doc.document_token,draft:doc.raw+" ",variantId:null,seed:20261023});
  assert(checked.result.valid);
  const itemSource=doc.pool_context.items[poolRich.items[0].item_id].sources[0];
  const itemPath=resolve(root,itemSource.path), itemBytes=await readFile(itemPath);
  try {
    const changed=JSON.parse(itemBytes); changed.id="w3a_removed_item"; await writeFile(itemPath,JSON.stringify(changed));
    const stale=await ipc("apply_document",{token:doc.document_token,reviewToken:checked.result.review_token,confirmed:true});
    assert.equal(stale.error?.code,"SOURCE_CHANGED"); assert.deepEqual(await readFile(resolve(root,poolTarget)),savedPool);
  } finally { await writeFile(itemPath,itemBytes); }
  checked=await ipc("validate_document",{token:doc.document_token,draft:doc.raw+" ",variantId:null,seed:20261023});
  assert(checked.result.valid);
  const invalidReview=await ipc("validate_document",{token:doc.document_token,draft:doc.raw,variantId:"../unsafe",seed:20261023});
  assert.equal(invalidReview.error?.code,"VARIANT_ID");
  const revoked=await ipc("apply_document",{token:doc.document_token,reviewToken:checked.result.review_token,confirmed:true});
  assert.equal(revoked.error?.code,"REVIEW_REQUIRED");
  receipt.checks.push("pool apply revalidates changed item dependencies; failed replacement validation revokes an older pool review");
  await page.getByRole("button",{name:"Close project",exact:true}).click(); await idle();
  await page.getByLabel("Repository directory").fill(root); await button("Open directory").click(); await idle();
  await page.getByLabel("Search ID, name or path").fill(buildingTarget); await page.locator(`[data-asset="${buildingTarget}"]`).click(); await idle();
  await page.getByLabel("Active layer").selectOption("specials"); await page.getByLabel("Placed record",{exact:true}).selectOption("0");
  await button(`Open pool ${poolId}`).click(); await idle();
  assert((await page.getByRole("navigation",{name:"Source trail"}).innerText()).includes(buildingId));
  await shot("reopened-chain"); await cleanCopy();
  receipt.checks.push("fresh project reopen resolves the complete saved structure → container → new pool → item chain");
}
